#!/usr/bin/env python3
"""Regenerate the C protocol layer from the CAN database.

The generated sources are committed so that a reviewer cloning the repo sees
real code and the firmware builds without a Python toolchain. Committing
generated code invites drift, so --check enforces the invariant in CI: if
bfmc.dbc and the committed output disagree, the build fails.

    python tools/generate_protocol.py            # regenerate in place
    python tools/generate_protocol.py --check    # fail if out of date

The generator itself is cantools, not something hand-rolled here. Writing a
fifth-rate DBC parser would be strictly worse than using the tool the
automotive Python ecosystem already standardised on.
"""
import argparse
import pathlib
import re
import subprocess
import sys
import tempfile

# cantools stamps the generation time into the file header, so two runs over an
# identical database still differ byte-for-byte. Drop that line before
# comparing, or the drift check can never pass.
BANNER = re.compile(r"^.*was generated by cantools version.*$", re.MULTILINE)

ROOT = pathlib.Path(__file__).resolve().parent.parent
DBC = ROOT / "dbc" / "bfmc.dbc"
OUT = ROOT / "firmware" / "common" / "protocol" / "generated"
ARTIFACTS = ("bfmc.h", "bfmc.c")


def generate(target: pathlib.Path) -> None:
    target.mkdir(parents=True, exist_ok=True)
    subprocess.run(
        [
            sys.executable, "-m", "cantools", "generate_c_source",
            "--database-name", "bfmc",
            # Single precision: the F446 has a single-precision FPU, so double
            # would silently pull in slow software floating point.
            "--use-float",
            "-o", str(target),
            str(DBC),
        ],
        check=True,
        stdout=subprocess.DEVNULL,
    )


def normalise(path: pathlib.Path) -> str:
    """File content with the volatile generator banner removed."""
    return BANNER.sub("", path.read_text(encoding="utf-8"))


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true",
                    help="verify the committed output matches the database")
    args = ap.parse_args()

    if not args.check:
        generate(OUT)
        print(f"regenerated {', '.join(ARTIFACTS)} in {OUT.relative_to(ROOT)}")
        return 0

    with tempfile.TemporaryDirectory() as tmp:
        fresh = pathlib.Path(tmp)
        generate(fresh)

        stale = []
        for name in ARTIFACTS:
            committed = OUT / name
            if not committed.exists():
                stale.append(f"{name} is missing")
                continue
            if normalise(committed) != normalise(fresh / name):
                stale.append(f"{name} differs from what bfmc.dbc generates")

    if stale:
        for item in stale:
            print(f"ERROR: {item}", file=sys.stderr)
        print("Run: python tools/generate_protocol.py", file=sys.stderr)
        return 1

    print("generated protocol code is in sync with bfmc.dbc")
    return 0


if __name__ == "__main__":
    sys.exit(main())
